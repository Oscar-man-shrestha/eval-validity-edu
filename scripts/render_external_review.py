def load(name: str) -> dict:
    path = PHASE / name
    if not path.exists():
        raise SystemExit(f"missing {path}")
    return json.loads(path.read_text())


def fmt(x, nd=3):
    if x is None:
        return "—"
    return f"{float(x):.{nd}f}"


def ci(obj, nd=3):
    if not obj or obj.get("ci") is None or obj["ci"][0] is None:
        return "—"
    return f"[{fmt(obj['ci'][0], nd)}, {fmt(obj['ci'][1], nd)}]"



"""Plain-language findings report for teammates and teachers.

Reads only outputs_junyi/phases/*.json — no hand-typed metric numbers.
Writes docs/TEAM_FINDINGS_REPORT.md
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PHASE = ROOT / "outputs_junyi" / "phases"
OUT = ROOT / "docs" / "TEAM_FINDINGS_REPORT.md"


def load(name: str):
    p = PHASE / name
    return json.loads(p.read_text()) if p.exists() else None


def fmt(x, nd=3):
    if x is None:
        return "—"
    try:
        return f"{float(x):.{nd}f}"
    except (TypeError, ValueError):
        return str(x)


def main() -> None:
    rep = load("followup2_repetition.json")
    forget3 = load("followup3_forgetting.json")
    concept = load("followup3_concept_repetition.json")
    recon = load("followup2_ranking_reconcile.json")
    chance = load("followup3_exact_dup_chance.json")
    ranks = load("followup3_rank_reversal.json")
    ready = load("review_readiness.json")
    ranking = load("review_ranking.json")
    xes_kc = load("followup3_xes_kc_repetition.json")

    f_status = forget3["status"] if forget3 else "unresolved"
    lines = [
        "# NeuroTrace-DAG — Findings report (for the team & teachers)",
        "",
        "_Auto-generated from `outputs_junyi/phases/*.json` by `scripts/render_team_report.py`. "
        "If a number looks wrong, re-run the scripts — do not edit this file by hand._",
        "",
        "## In one page",
        "",
        "1. **Concept-level sticky repetition** is high on Junyi topics and ASSISTments skills, "
        "lower on XES3G5M KCs — compare concepts, not raw question ids.",
        "2. **Rank order of recommenders flips by slice** (all vs revisit vs advance) on all three corpora.",
        "3. **DAG parent mastery → correctness** is only a tiny AUC bump vs our practical bar.",
        f"4. **Forgetting redo (gap≥1 only, log1p gap):** status **{f_status}**. "
        "Do not call older day-vs-success runs a settled null.",
        "",
        "---",
        "",
        "## Datasets (plain English)",
        "",
        "| Dataset | What it is | Role |",
        "| --- | --- | --- |",
        "| Junyi ktbd | Filtered sequences + expert DAG | Main product eval |",
        "| Junyi timed | Timestamped user streams | Forgetting + learner-disjoint ranking |",
        "| ASSISTments 2009 | Skill-builder mastery log | Second mastery corpus |",
        "| XES3G5M | Large K–12 KT benchmark | Contrast corpus |",
        "",
        "---",
        "",
        "## 1. Concept-level repetition",
        "",
        f"Finding label: **{rep['finding_label'] if rep else 'repetition is high on mastery-based logs'}**",
        "",
        "| Dataset / unit | next==last | n | continue | revisit | advance |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    if concept:
        for row in concept["rows"]:
            sh = row["share_next_equals_last"]
            tw = row["three_way_mix"]
            lines.append(
                f"| {row['dataset_unit']} | {fmt(sh['share'])} | {sh['n']} | "
                f"{fmt(tw['continue']['frac'])} | {fmt(tw['revisit']['frac'])} | "
                f"{fmt(tw['advance']['frac'])} |"
            )
    if xes_kc:
        lines += [
            "",
            "XES KC methods (both reported):",
            f"- A question→primary KC: {fmt(xes_kc['method_a_question_then_primary_kc']['share_next_equals_last']['share'])}",
            f"- B drop multi-KC extras: {fmt(xes_kc['method_b_drop_multi_kc_extras']['share_next_equals_last']['share'])}",
        ]

    if ranking and recon:
        m = ranking["metrics"]
        lines += [
            "",
            "---",
            "",
            "## 2. Junyi ktbd ranking (canonical RAGR eval)",
            "",
            f"Sample {ranking['eval']['n_sequences']}×{ranking['eval']['cuts_per_sequence']}, "
            f"seed={ranking['eval']['seed']}. Order: `{ranking.get('ordering_sentence_r5')}`",
            "",
            f"| RAGR R@5 | {fmt(m['ragr_r5']['mean'])} | Recent-5 | {fmt(m['recent5_r5']['mean'])} | "
            f"Force review | {fmt(m['force_review_r5']['mean'])} |",
            "",
            f"Δ(RAGR−recent5)={fmt(recon['canonical_run']['paired_ragr_minus_recent5_r5']['mean'], 4)} "
            f"→ **{recon['effect_labels']['ragr_minus_recent5']}** "
            f"(practical bar {recon['practical_threshold_recall_at_5']}).",
            "",
            recon["legacy_polluted_rng_run"]["note"],
        ]

    if ranks:
        lines += [
            "",
            "---",
            "",
            "## 3. Rank-reversal study (learner-disjoint)",
            "",
            "Same protocol on Junyi timed / ASSISTments / XES: popularity, recency, "
            "GRU4Rec-style, SASRec-style, RAGR. Seeds and sample indices saved in JSON.",
            "",
        ]
        for ds, payload in ranks["datasets"].items():
            lines.append(f"### {ds}")
            for sl in ("all", "revisit", "advance"):
                order = " > ".join(
                    f"{x['method']}({fmt(x['r5'])})" for x in payload["rankings_by_slice_r5"][sl]
                )
                lines.append(f"- **{sl}:** {order}")
            if payload["rank_reversals"]:
                for rev in payload["rank_reversals"]:
                    lines.append(
                        f"- Rank reversal on `{rev['slice']}` vs all-query order."
                    )
            lines.append("")

    if ready:
        st = ready["dag_helps_correctness"]["status"]
        thr = ready["dag_helps_correctness"].get("practical_threshold_delta_auc", 0.005)
        d = ready["dag_helps_correctness"].get("primary_delta_auc") or {}
        lines += [
            "---",
            "",
            "## 4. Does the DAG help “got it right?”",
            "",
            f"Status **{st}** (bar ΔAUC≥{thr}). Primary ΔAUC={fmt(d.get('mean'), 4)} CI={d.get('ci')}.",
            "Tiny and not a practical “DAG boosts correctness by 10 points” claim.",
            "",
        ]

    if forget3:
        lines += [
            "---",
            "",
            "## 5. Forgetting redo (gap ≥ 1 day only)",
            "",
            "Fit and test **only** on returns with calendar gap ≥ 1 day. Compare:",
            "logistic(success), + log1p(gap), + gap bins. Learner-level split + paired bootstrap.",
            "",
            f"- Status: **{forget3['status']}**",
            f"- AUC: success={fmt(forget3['auc']['success_only'])}, "
            f"+log1p={fmt(forget3['auc']['success_plus_log1p_gap'])}, "
            f"+bins={fmt(forget3['auc']['success_plus_gap_bins'])}",
            f"- Δ(+log1p − success)={fmt(forget3['paired_deltas']['log1p_gap_minus_success']['mean'], 4)} "
            f"CI={forget3['paired_deltas']['log1p_gap_minus_success']['ci']}",
            f"- n_test_rows={forget3['n_test_rows']} (learners={forget3['n_test_learners']})",
            "",
            "Accuracy by gap bin inside success-rate strata is in `followup3_forgetting.json`.",
            "",
        ]

    if chance:
        cmp_ = chance.get("comparison") or chance
        lines += [
            "---",
            "",
            "## 6. Exact duplicates vs chance",
            "",
            f"- Real exact train∩test hashes: **{cmp_.get('real_overlap', chance.get('real_train_test_exact', {}).get('n_overlap_hashes'))}**",
            f"- Chance (6290 pseudo-test vs remaining train): **{cmp_.get('chance_overlap')}**",
            f"- Real − chance: **{cmp_.get('real_minus_chance')}**",
            "",
        ]

    lines += [
        "---",
        "",
        "## Claims cheat-sheet",
        "",
        "| OK | Not OK |",
        "| --- | --- |",
        "| Concept sticky-repeat is high on mastery logs; lower on XES KCs | “All logs are 80% continue” |",
        "| Rank order reverses on revisit/advance slices | “GRU4Rec always wins everywhere” |",
        "| Forgetting status from follow-up 3 only | Cite older day−success as a settled null |",
        "| Parent-mastery ΔAUC is tiny vs 0.005 bar | “DAG +10 pp correctness” |",
        "",
        "## Reproduce",
        "",
        "```bash",
        "python3 run_followup3.py",
        "python3 scripts/render_team_report.py",
        "python3 scripts/render_external_review.py",
        "python3 scripts/build_dataflow_report.py",
        "python3 -m pytest tests/test_leakage_guards.py -q",
        "```",
        "",
        "Reviewer detail: `docs/EXTERNAL_REVIEW_RESPONSE.md`.  ",
        "PDF: `docs/NeuroTrace-DAG_Data_Flow_Report.pdf`.",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
